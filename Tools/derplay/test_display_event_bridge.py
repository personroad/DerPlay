"""Source guards for the experimental transport bridge; not a live CarPlay test."""
from pathlib import Path
import unittest
ROOT=Path(__file__).resolve().parents[2]
class DisplayEventBridgeTests(unittest.TestCase):
    def test_runtime_transport_wiring(self):
        s=(ROOT/'App/CarPlayMediaSession.swift').read_text()
        self.assertIn('self.displayReplies.resolve(sequence: seq, status: status)',s)
        self.assertIn('displayReplies.register(sequence: sequence, completion: completion)',s)
        self.assertIn('finish(sequence: sequence, outcome: .timedOut)',s)
        self.assertIn('finish(outcome: .channelClosed)',s)
        self.assertIn('finish(outcome: .writeFailed)',s)
    def test_production_remains_single_area(self):
        s=(ROOT/'App/CarPlayMediaSession.swift').read_text()
        self.assertIn('advertisedDisplayAreaCount: Int = 1',s)
        self.assertIn('advertisedDisplayAreaCount > 1',s)
        self.assertIn('advertisedDisplayAreaCount: state.declaredDisplayAreaCount',(ROOT/'App/NativeReceiver.swift').read_text())
        config=(ROOT/'App/ReceiverConfiguration.swift').read_text()
        self.assertIn('var experimentalBrowserViewAreas = false',config)
        self.assertIn('guard experimentalBrowserViewAreas, browserOnlyOutput else { return nil }',config)
        self.assertNotIn('DERPLAY_EXPERIMENTAL_VIEW_AREAS',config)
        self.assertIn('display.merge(profile.displayFields)',(ROOT/'App/CarPlayInfo.swift').read_text())
        self.assertIn('"viewAreas": [view], "initialViewArea": 0',(ROOT/'App/CarPlayInfo.swift').read_text())
        for f in (ROOT/'App').glob('*.swift'):
            self.assertEqual(f.read_text().count('sendTrackedDisplayCommand('), 1 if f.name in ('CarPlayMediaSession.swift','NativeReceiver.swift') else 0, f.name)
    def test_declared_profile_is_session_local(self):
        s=(ROOT/'App/NativeReceiver.swift').read_text()
        self.assertIn('var declaredDisplayAreaCount = 1',s)
        self.assertIn('let displays = info["displays"]',s)
        self.assertIn('state.declaredDisplayAreaCount = count',s)
        self.assertIn('state.media?.noteAdvertisedDisplayAreas(count)',s)
        m=(ROOT/'App/CarPlayMediaSession.swift').read_text()
        self.assertIn('private var advertisedDisplayAreaCount: Int',m)
        self.assertIn('guard browserDisplayDiagnostics, count > 1, advertisedDisplayAreaCount == 1',m)
        self.assertIn('advertisedDisplayAreaCount = count',m)
    def test_browser_recommendation_is_generation_guarded(self):
        s=(ROOT/'App/NativeReceiver.swift').read_text()
        self.assertIn('let displayProfile = configuration.dynamicDisplayProfile',s)
        self.assertIn('self.generation == displayGeneration',s)
        self.assertIn('displayProfile.recommendedRegion(viewportWidth: display.width, viewportHeight: display.height',s)
        self.assertIn('self.tryBrowserDisplayProbe(profile: displayProfile)',s)
        self.assertIn('browserRegionRecommendation = nil; browserRegionViewer = nil',s)
    def test_opt_in_probe_is_one_shot_and_touch_safe(self):
        s=(ROOT/'App/NativeReceiver.swift').read_text()
        self.assertIn('touchSlots.isEmpty else { return }',s)
        self.assertIn('active.count == 1',s)
        self.assertIn('state.declaredDisplayAreaCount == profile.regions.count',s)
        self.assertIn('let command = profile.command(index: index), state.displayProbe.begin(index: index)',s)
        self.assertIn('self.generation == run',s)
        self.assertIn('state.media === media',s)
        self.assertIn('guard !self.sessions.values.contains(where: { $0.displayProbe.blocksTouches })',s)
        self.assertIn('presentation unverified',s)
        self.assertIn('no automatic retry',s)
        media=(ROOT/'App/CarPlayMediaSession.swift').read_text()
        self.assertIn('hasEventChannel && video != nil && videoPackets > 0',media)
        probe=(ROOT/'App/DerPlayDisplayEventReplies.swift').read_text()
        self.assertIn('guard self.index == nil, index > 0',probe)
    def test_unified_workflow_and_runtime_opt_in(self):
        workflow=(ROOT/'.github/workflows/build-ipa.yml').read_text()
        self.assertNotIn('experimental_view_areas',workflow)
        self.assertNotIn('DERPLAY_EXPERIMENTAL_VIEW_AREAS',workflow)
        self.assertNotIn('DerPlay-IPA-experimental-view-areas',workflow)
        self.assertEqual(workflow.count('name: DerPlay-IPA'),1)
        ui=(ROOT/'App/ReceiverViewController.swift').read_text()
        self.assertIn('config.experimentalBrowserViewAreas = outputMode == .browser && UserDefaults.standard.bool',ui)
        section=ui.split('private func browserExperimentsPage()',1)[1].split('private func diagnosticsSection()',1)[0]
        self.assertIn('guard !self.running, !self.waitingForNetwork',section)
        self.assertIn('UserDefaults.standard.set(!enabled, forKey: key)',section)
        self.assertIn('触控暂停至会话结束',section)
    def test_probe_write_diagnostics_and_capability(self):
        media=(ROOT/'App/CarPlayMediaSession.swift').read_text()
        sockets=(ROOT/'App/MediaSockets.swift').read_text()
        self.assertIn('peerProposedViewAreas = proposed.contains("viewAreas")',media)
        self.assertIn('browserDisplayDiagnostics && peerProposedViewAreas &&',media)
        self.assertIn('response without valid CSeq',media)
        self.assertIn('try event.send(encrypted, onWritten:',media)
        self.assertIn('socket write completed CSeq=',media)
        self.assertIn('delivery unverified',media)
        self.assertIn('remaining?.isEmpty == true',sockets)
        self.assertIn('onWritten?()',sockets)
    def test_unsequenced_response_is_tentative(self):
        media=(ROOT/'App/CarPlayMediaSession.swift').read_text()
        replies=(ROOT/'App/DerPlayDisplayEventReplies.swift').read_text()
        self.assertIn('eventOrder.sent(sequence)',media)
        self.assertIn('request.headers["cseq"] == nil',media)
        self.assertIn('outstanding.count == 1',replies)
        self.assertIn('outcome: .unsequencedResponse(status)',replies)
    def test_post_probe_refresh_is_session_guarded(self):
        native=(ROOT/'App/NativeReceiver.swift').read_text()
        block=native.split('guard DerPlayDisplayEventReplies.shouldRefreshVideo(after: outcome)',1)[1].split('if !sent',1)[0]
        self.assertIn('.milliseconds(350)',block)
        self.assertIn('self.generation == run',block)
        self.assertIn('state.media === media',block)
        self.assertEqual(block.count('media.requestKeyFrame()'),1)
        self.assertIn('presentation unverified',block)
        media=(ROOT/'App/CarPlayMediaSession.swift').read_text()
        self.assertIn('if done != nil, self.browserDisplayDiagnostics { self.eventOrder.invalidate() }',media)
    def test_startup_diagnostics_are_experimental_and_passive(self):
        media=(ROOT/'App/CarPlayMediaSession.swift').read_text()
        native=(ROOT/'App/NativeReceiver.swift').read_text()
        diagnostics=(ROOT/'App/DerPlayDisplayEventReplies.swift').read_text()
        self.assertIn('guard browserDisplayDiagnostics else { return }',media)
        self.assertIn('state.media?.noteRecord()',native)
        self.assertIn('DerPlay event diagnostic: TEARDOWN phase=',media)
        self.assertIn('DerPlay event diagnostic: response status=',media)
        self.assertIn('invalidSequence: sequence == nil',media)
        self.assertIn('if order.count == 128',diagnostics)
        self.assertIn('default: return "other"',diagnostics)
        self.assertIn('if status != 200 || !attribution.hasSuffix("type=hidSendReport")',media)
    def test_project_includes_bridge(self):
        self.assertIn('App/DerPlayDisplayEventReplies.swift',(ROOT/'TDSCarKit.xcodeproj/project.pbxproj').read_text())
        self.assertIn("root.glob('App/*.swift')",(ROOT/'Tools/generate_project.py').read_text())
if __name__=='__main__': unittest.main()
